def read_gen4_str(data: bytes, off: int, max_chars: int) -> str:
    chars: list[str] = []
    for i in range(max_chars):
        code = u16(data, off + i * 2)
        if code == 0xFFFF:
            break
        if code < len(_G4_CHAR_TABLE):
            uni = _G4_CHAR_TABLE[code]
            if uni != 0:
                chars.append(chr(uni))
    return sanitize_pkm_string("".join(chars))
