def national_from_internal1(internal: int) -> int:
    if internal < 0 or internal >= len(_TABLE1):
        return 0
    return _TABLE1[internal]


def parse_gen1(raw: bytes) -> dict:
    out = default_out("gen1")
    internal = raw[0]
    out["species_id"] = national_from_internal1(internal)
    out["tid"] = u16_be(raw, 0x0C)
    out["held_item_id"] = raw[0x07]
    out["moves"] = [raw[0x08], raw[0x09], raw[0x0A], raw[0x0B]]
    out["move_pp"] = [raw[0x1D] & 0x3F, raw[0x1E] & 0x3F, raw[0x1F] & 0x3F, raw[0x20] & 0x3F]
    dv16 = u16_be(raw, 0x1B)
    out["ivs"] = ivs_from_dv16_be(dv16)
    out["evs"] = {
        "hp": u16_be(raw, 0x11), "atk": u16_be(raw, 0x13),
        "def": u16_be(raw, 0x15), "spe": u16_be(raw, 0x17),
        "spa": u16_be(raw, 0x19), "spd": u16_be(raw, 0x19),
    }
    out["level"] = raw[0x21] if len(raw) > 0x21 else raw[3]
    out["met_level"] = raw[3]
    out["shiny"] = is_shiny_gen12(dv16)
    return out
